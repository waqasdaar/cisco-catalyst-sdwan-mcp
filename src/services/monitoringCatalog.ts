/*
 * Monitoring and troubleshooting views of the Cisco Catalyst SD-WAN Manager 26.2 API.
 * Each view is one OpenAPI operation (path as in the spec, without /dataservice). At call time the operation is looked
 * up in the connected Manager's own spec, so parameters are validated there and deprecated or state-changing
 * operations are refused. `npm run verify:monitoring` checks every view against the bundled 26.2.1 spec.
 */

export interface MonitoringView {
  path: string;
  /** Path of the vManage cached (synced) copy, used when synced: true. */
  synced?: string;
  /** POST for read-only queries that take a body (statistics, alarms, events). */
  method?: 'GET' | 'POST';
}

type ViewTable = Record<string, string | MonitoringView>;

export const view = (v: string | MonitoringView): MonitoringView => (typeof v === 'string' ? { path: v } : v);
const post = (path: string): MonitoringView => ({ path, method: 'POST' });
const synced = (path: string, syncedPath: string): MonitoringView => ({ path, synced: syncedPath });

